//! # Distribution fitting
//!
//! Maximum-likelihood fits of the skewed return distributions in
//! `stochastic-rs-distributions` — Johnson SU, Hansen's skewed Student-t
//! (with location and scale) and the variance gamma — each maximising
//! $\sum_i \log f(x_i \mid \theta)$ with the distribution's own closed-form
//! density in unconstrained coordinates (log scales, $\eta = 2 + e^{\vartheta}$,
//! $\lambda = \tanh\vartheta$), from the best point of a small starting grid
//! through a Nelder–Mead simplex with one restart. Standard errors are the
//! inverse observed information from a central-difference Hessian at the
//! optimum, as in [`crate::evt`].
//!
//! $$
//! \hat\theta = \arg\max_\theta \sum_{i=1}^{n}\log f(x_i \mid \theta),\qquad
//! \widehat{\mathrm{Cov}}(\hat\theta) = \bigl(-\nabla^2\ell(\hat\theta)\bigr)^{-1}.
//! $$
//!
//! # References
//! - Johnson, "Systems of Frequency Curves Generated by Methods of
//!   Translation", Biometrika, 36(1/2), 149-176 (1949).
//!   DOI: 10.1093/biomet/36.1-2.149
//! - Hansen, "Autoregressive Conditional Density Estimation", International
//!   Economic Review, 35(3), 705-730 (1994). DOI: 10.2307/2527081
//! - Madan, Carr, Chang, "The Variance Gamma Process and Option Pricing",
//!   European Finance Review, 2(1), 79-105 (1998). DOI: 10.1023/A:1009703431535

