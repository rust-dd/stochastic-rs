/// Within `4e-15 · max(1, |ln F|) · F` below ½ and `1e-15` above, where `1 − F` cannot carry the upper tail; exact at 0.
fn cdf_agrees(got: f64, want: f64) -> bool {
  if want == 0.0 || want.is_infinite() {
    return got == want;
  }
  let tol = if want <= 0.5 {
    4e-15 * want.ln().abs().max(1.0) * want
  } else {
    1e-15
  };
  (got - want).abs() <= tol
}

/// Within `4e-15 · max(1, κ) · max(1, |ln p̃|) · |q|`, the error a relative rounding of `p̃` carries; a zero or infinite
/// truth exactly.
fn quantile_agrees(got: f64, want: f64, p: f64, kappa: f64) -> bool {
  if want == 0.0 || want.is_infinite() {
    return got == want;
  }
  let tol = 4e-15 * kappa.max(1.0) * p.min(1.0 - p).ln().abs().max(1.0) * want.abs();
  (got - want).abs() <= tol
}

fn report(kind: &str, total: usize, failures: Vec<String>) {
  assert!(
    failures.is_empty(),
    "{kind}: {} of {total} rows miss\n{}",
    failures.len(),
    failures.join("\n")
  );
}

#[test]
fn the_t_cdf_matches_mpmath() {
  let failures = T_CDF
    .iter()
    .filter_map(|&(nu, x, want)| {
      let got = SimdStudentT::<f64>::new(nu).cdf(x).unwrap();
      (!cdf_agrees(got, want)).then(|| format!("ν = {nu:e}, x = {x:e}: {got:e}, want {want:e}"))
    })
    .collect();
  report("t cdf", T_CDF.len(), failures);
}

#[test]
fn the_t_quantile_matches_mpmath() {
  let failures = T_QUANTILE
    .iter()
    .filter_map(|&(nu, p, want, kappa)| {
      let got = SimdStudentT::<f64>::new(nu).quantile(p).unwrap();
      (!quantile_agrees(got, want, p, kappa))
        .then(|| format!("ν = {nu:e}, p = {p:e}: {got:e}, want {want:e}"))
    })
    .collect();
  report("t quantile", T_QUANTILE.len(), failures);
}

/// The upper half is the lower one reflected: `q(p) = −q(1 − p)` to the bit, `1 − p` exact for `p > ½`.
#[test]
fn the_t_quantile_is_odd_to_the_bit() {
  let levels = T_QUANTILE.iter().filter(|row| row.1 > 0.5);
  let failures: Vec<String> = levels
    .clone()
    .filter_map(|&(nu, p, _, _)| {
      let law = SimdStudentT::<f64>::new(nu);
      let (upper, lower) = (law.quantile(p).unwrap(), law.quantile(1.0 - p).unwrap());
      (upper.to_bits() != (-lower).to_bits())
        .then(|| format!("ν = {nu:e}, p = {p:e}: {upper:e} against −{lower:e}"))
    })
    .collect();
  report("t quantile symmetry", levels.count(), failures);
}

#[test]
fn the_chi_square_quantile_and_median_match_mpmath() {
  let quantiles = CHI2_QUANTILE.iter().filter_map(|&(k, p, want, kappa)| {
    let got = SimdChiSquared::<f64>::new(k).quantile(p).unwrap();
    (!quantile_agrees(got, want, p, kappa))
      .then(|| format!("k = {k:e}, p = {p:e}: {got:e}, want {want:e}"))
  });
  let medians = CHI2_MEDIAN.iter().filter_map(|&(k, want, kappa)| {
    let got = SimdChiSquared::<f64>::new(k).median().unwrap();
    (!quantile_agrees(got, want, 0.5, kappa))
      .then(|| format!("k = {k:e}, median: {got:e}, want {want:e}"))
  });
  report(
    "χ² quantile and median",
    CHI2_QUANTILE.len() + CHI2_MEDIAN.len(),
    quantiles.chain(medians).collect(),
  );
}

/// `P(T ≤ −|x|) ≤ ½` holds to the bit, so the cdf never crosses `F(0) = ½` the wrong way where the lower tail's factor
/// rounds past 1.
#[test]
fn the_t_cdf_is_monotone_through_zero_at_tiny_nu() {
  let magnitudes: Vec<f64> = (-3000..=3000)
    .map(|i| 10f64.powf(f64::from(i) / 10.0))
    .collect();
  for nu in [1e-300, 1e-20, 1e-15] {
    let law = SimdStudentT::<f64>::new(nu);
    let centre = law.cdf(0.0).unwrap();
    let crossing = magnitudes
      .iter()
      .find(|&&m| law.cdf(-m).unwrap() > centre || law.cdf(m).unwrap() < centre);
    assert!(crossing.is_none(), "ν = {nu:e}: |x| = {crossing:?}");
  }
}
