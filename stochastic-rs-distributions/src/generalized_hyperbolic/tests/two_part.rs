use super::*;

#[derive(Clone, Copy)]
enum At {
  Pdf,
  Mgf,
}

/// mpmath at 60 and 120 digits where a `K` overflows at order −5 or `δγ` is subnormal at order ±60, which a one-part sum of
/// logarithms or a subnormal clock read up to `7.7e-11` off, or NaN.
#[test]
fn large_logarithms_and_subnormal_clocks_keep_their_digits() {
  use At::Mgf;
  use At::Pdf;
  for (at, lambda, alpha, beta, delta, x, want) in [
    (
      Pdf,
      -5.0,
      0.001,
      0.0,
      1e-155,
      -3.000_000_000_000_000_2e-155,
      3.891_083_839_660_308e+149,
    ),
    (
      Pdf,
      -5.0,
      0.001,
      0.0005,
      1e-155,
      -3.000_000_000_000_000_2e-155,
      3.891_083_839_660_308e+149,
    ),
    (
      Pdf,
      -5.0,
      0.001,
      -0.000_900_000_000_000_000_1,
      1e-155,
      -3.000_000_000_000_000_2e-155,
      3.891_083_839_660_308e+149,
    ),
    (Pdf, -5.0, 1e-158, 0.0, 1e-100, 0.0, 1.230_468_75e+100),
    (
      Pdf,
      -5.0,
      1e-158,
      0.0,
      1e-100,
      1e-100,
      2.718_977_491_134_795_7e+98,
    ),
    (
      Pdf,
      -5.0,
      1e-158,
      0.0,
      1e-100,
      -3e-100,
      3.891_083_839_660_310_6e+94,
    ),
    (Pdf, -5.0, 1e-158, 0.0, 1.0, -3.0, 3.891_083_839_660_311e-06),
    (
      Pdf,
      -5.0,
      1e-158,
      5e-159,
      1e-100,
      1e-100,
      2.718_977_491_134_795_7e+98,
    ),
    (
      Pdf,
      -5.0,
      1e-158,
      5e-159,
      1e-100,
      -3e-100,
      3.891_083_839_660_310_6e+94,
    ),
    (
      Pdf,
      -60.0,
      1e-155,
      0.0,
      1e-155,
      1e-155,
      2.674_737_591_711_644_4e+137,
    ),
    (
      Pdf,
      -60.0,
      1e-155,
      0.0,
      1e-155,
      -3.000_000_000_000_000_2e-155,
      1.379_100_510_223_621e+95,
    ),
    (Pdf, -60.0, 1e-155, 0.0, 1e-155, -4e+155, 0.0),
    (
      Pdf,
      60.0,
      1e-155,
      0.0,
      1e-155,
      0.0,
      3.664_788_852_610_927e-157,
    ),
    (
      Pdf,
      60.0,
      1e-155,
      0.0,
      1e-155,
      1e-155,
      3.664_788_852_610_927e-157,
    ),
    (
      Pdf,
      60.0,
      1e-155,
      0.0,
      1e-155,
      -3.000_000_000_000_000_2e-155,
      3.664_788_852_610_927e-157,
    ),
    (
      Pdf,
      60.0,
      1e-155,
      0.0,
      1e-155,
      1e+155,
      3.649_161_358_347_082_4e-157,
    ),
    (
      Pdf,
      60.0,
      1e-155,
      0.0,
      1e-155,
      -4e+155,
      3.422_718_925_507_416e-157,
    ),
    (
      Mgf,
      60.0,
      1e-155,
      0.0,
      1e-155,
      4e-156,
      34_933.559_229_964_05,
    ),
    (
      Mgf,
      60.0,
      1e-155,
      0.0,
      1e-155,
      -4e-156,
      34_933.559_229_964_05,
    ),
    (
      Pdf,
      -60.0,
      1e-155,
      5e-156,
      1e-155,
      1e-155,
      2.674_737_591_711_644_4e+137,
    ),
    (
      Pdf,
      -60.0,
      1e-155,
      5e-156,
      1e-155,
      -3.000_000_000_000_000_2e-155,
      1.379_100_510_223_621e+95,
    ),
    (Pdf, -60.0, 1e-155, 5e-156, 1e-155, -4e+155, 0.0),
    (
      Pdf,
      60.0,
      1e-155,
      5e-156,
      1e-155,
      0.0,
      1.168_758_443_163_395e-164,
    ),
    (
      Pdf,
      60.0,
      1e-155,
      5e-156,
      1e-155,
      1e-155,
      1.168_758_443_163_395e-164,
    ),
    (
      Pdf,
      60.0,
      1e-155,
      5e-156,
      1e-155,
      -3.000_000_000_000_000_2e-155,
      1.168_758_443_163_395e-164,
    ),
    (
      Pdf,
      60.0,
      1e-155,
      5e-156,
      1e-155,
      1e+155,
      1.918_739_922_475_345e-164,
    ),
    (
      Pdf,
      60.0,
      1e-155,
      5e-156,
      1e-155,
      -4e+155,
      1.477_263_868_907_121e-165,
    ),
    (
      Mgf,
      60.0,
      1e-155,
      5e-156,
      1e-155,
      2e-156,
      11_206_377_229.776_278,
    ),
    (
      Mgf,
      60.0,
      1e-155,
      5e-156,
      1e-155,
      -6e-156,
      5.828_598_331_575_288e-08,
    ),
    (
      Pdf,
      -5.0,
      1.6e-154,
      8e-155,
      1e-100,
      -3e-100,
      3.891_083_839_660_310_6e+94,
    ),
    (Pdf, -5.0, 1e-152, 0.0, 1e-100, 0.0, 1.230_468_75e+100),
    (Pdf, -5.0, 1e-152, 5e-153, 1e-100, 0.0, 1.230_468_75e+100),
  ] {
    let gh = SimdGeneralizedHyperbolic::<f64>::new(lambda, alpha, beta, delta, 0.0);
    let got = match at {
      Pdf => gh.pdf(x),
      Mgf => gh.moment_generating_function(x),
    }
    .unwrap();
    if want == 0.0 {
      assert_eq!(got, 0.0, "GH({lambda}, {alpha}, {beta}, {delta}) at {x:e}");
    } else {
      assert!(
        close(got, want, 4e-13),
        "GH({lambda}, {alpha}, {beta}, {delta}) at {x:e}: {got:e}"
      );
    }
  }
}
