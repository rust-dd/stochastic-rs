use super::*;
use crate::special::gamma_ratio_half;

fn tail(nu: f64, x: f64) -> StudentTail {
  student_tail(nu, gamma_ratio_half(0.5 * nu), x)
}

/// `P(T ≤ −x)` within the law's cdf bar, `4e-15 · max(1, |ln F|) · F`, and exactly at 0.
fn agrees(got: f64, want: f64) -> bool {
  if want == 0.0 {
    return got == 0.0;
  }
  (got - want).abs() <= 4e-15 * want.ln().abs().max(1.0) * want
}

