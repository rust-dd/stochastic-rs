/// The halves meet at the centre and at the ends: `½` at `x = ±0`, `0` and `1` at `x = ±∞`; where the tail underflows its
/// logarithm stays finite (mpmath at 60 and 120 digits at `ν = 4`, `x = 1e200`).
#[test]
fn the_halves_meet_at_the_centre_and_the_ends() {
  for nu in [5e-300, 0.01, 4.0, 1e5, 1e300] {
    let centre = tail(nu, 0.0);
    assert_eq!((centre.lower(), centre.upper()), (0.5, 0.5), "ν = {nu}");
    let end = tail(nu, f64::INFINITY);
    assert_eq!((end.lower(), end.upper()), (0.0, 1.0), "ν = {nu}");
  }
  let far = tail(4.0, 1e200);
  assert_eq!(far.lower(), 0.0);
  let want = -1840.9694621065684;
  assert!(
    (far.ln_lower() - want).abs() <= 4e-15 * -want,
    "{}",
    far.ln_lower()
  );
}
